import { createHash } from 'node:crypto';
import { Resvg } from '@resvg/resvg-js';
import { assertSafeText, assertSafeValue } from './safety.js';

export const MAX_ARTIFACT_FILES = 3;
export const MAX_ARTIFACT_BYTES = 1024 * 1024;
export const MAX_ARTIFACT_TOTAL_BYTES = 3 * MAX_ARTIFACT_BYTES;
const MARKER = 'OWAUA_ARTIFACT:';
const TEXT_TYPES = { txt: 'text/plain', md: 'text/markdown', csv: 'text/csv', json: 'application/json',
  py: 'text/x-python', js: 'text/javascript', ts: 'text/plain', css: 'text/css', html: 'text/html' };
const safeName = name => typeof name === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9 _.\-]{0,79}$/.test(name) && !name.includes('..');
const invalid = () => new Error('Invalid export. Use a safe filename and a supported file of at most 1 MiB.');

export const ARTIFACT_INSTRUCTIONS = `When the user requests downloadable data, code, reports or charts, use export_file for UTF-8 text/CSV/JSON/code, or export_chart for a line/bar PNG chart from verified data. Compute numerical analysis with code_interpreter before exporting; chart drawing never executes Python locally. For an actual file generated by hosted Python (including matplotlib PNG, PDF or XLSX), emit one stdout line per file as 'OWAUA_ARTIFACT:' followed by JSON with filename (basename only), mime_type and base64 (standard base64 of the actual file bytes). Example Python: import base64,json; print('OWAUA_ARTIFACT:'+json.dumps({'filename':'result.csv','mime_type':'text/csv','base64':base64.b64encode(csv_text.encode()).decode()})). Exports are at most 3 files, 1 MiB per file, 3 MiB combined. Do not put base64 in the final answer. Never claim an attachment exists from a sandbox path or invented download URL. Only describe exports after a successful tool result or successful Python execution.`;

function decodeBase64(value) {
  if (typeof value !== 'string' || value.length > Math.ceil(MAX_ARTIFACT_BYTES / 3) * 4 ||
    !value.length || value.length % 4 !== 0 || !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(value)) throw invalid();
  const bytes = Buffer.from(value, 'base64');
  if (bytes.toString('base64') !== value) throw invalid();
  return bytes;
}
function validatedArtifact(name, bytes, encoding) {
  if (!safeName(name) || !Buffer.isBuffer(bytes) || !bytes.length || bytes.length > MAX_ARTIFACT_BYTES) throw invalid();
  assertSafeText(name);
  const extension = name.split('.').at(-1).toLowerCase();
  let contentType;
  if (Object.hasOwn(TEXT_TYPES, extension)) {
    contentType = TEXT_TYPES[extension];
    const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
    assertSafeText(text);
    if (text.includes('\0')) throw invalid();
    if (extension === 'json') JSON.parse(text);
  } else if (extension === 'png') {
    if (encoding !== 'base64' || bytes.length < 45 || !bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) ||
      bytes.toString('ascii', 12, 16) !== 'IHDR' || bytes.readUInt32BE(16) < 1 || bytes.readUInt32BE(16) > 8192 ||
      bytes.readUInt32BE(20) < 1 || bytes.readUInt32BE(20) > 8192 || bytes.toString('ascii', bytes.length - 8, bytes.length - 4) !== 'IEND') throw invalid();
    contentType = 'image/png';
  } else if (extension === 'pdf') {
    if (encoding !== 'base64' || bytes.toString('ascii', 0, 5) !== '%PDF-' || !bytes.subarray(-1024).includes(Buffer.from('%%EOF'))) throw invalid();
    contentType = 'application/pdf';
  } else if (extension === 'xlsx') {
    if (encoding !== 'base64' || !bytes.subarray(0, 4).equals(Buffer.from([80, 75, 3, 4])) ||
      !bytes.includes(Buffer.from('[Content_Types].xml')) || !bytes.includes(Buffer.from('xl/workbook.xml'))) throw invalid();
    contentType = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
  } else throw invalid();
  return { name, attachment: bytes, contentType };
}

export function exportFile({ filename, content, encoding = 'utf8', ...extra }) {
  if (Object.keys(extra).length || !['utf8', 'base64'].includes(encoding) || typeof content !== 'string' ||
    encoding === 'utf8' && content.length > MAX_ARTIFACT_BYTES) throw invalid();
  return validatedArtifact(filename, encoding === 'utf8' ? Buffer.from(content) : decodeBase64(content), encoding);
}

const escape = text => String(text).replace(/[&<>"']/g, value => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[value]);
const COLORS = ['#3879de', '#d85c3a', '#299268', '#8a5dc6'];
export function exportChart({ title, x_label = '', y_label = '', series, chart_type = 'line', ...extra }) {
  assertSafeValue({ title, x_label, y_label, series });
  if (Object.keys(extra).length || !['line', 'bar'].includes(chart_type) ||
    [title, x_label, y_label].some(label => typeof label !== 'string' || label.length > 120) ||
    !Array.isArray(series) || !series.length || series.length > 4) throw invalid();
  const labels = [];
  const allValues = [];
  for (const item of series) {
    if (!item || typeof item !== 'object' || Object.keys(item).sort().join(',') !== 'name,points' ||
      typeof item.name !== 'string' || !item.name || item.name.length > 80 || !Array.isArray(item.points) ||
      !item.points.length || item.points.length > 200) throw invalid();
    const seen = new Set();
    for (const point of item.points) {
      if (!point || typeof point !== 'object' || Object.keys(point).sort().join(',') !== 'x,y' ||
        !['string', 'number'].includes(typeof point.x) || typeof point.x === 'number' && !Number.isFinite(point.x) ||
        String(point.x).length > 80 || typeof point.y !== 'number' || !Number.isFinite(point.y) || Math.abs(point.y) > 1e15 ||
        seen.has(String(point.x))) throw invalid();
      seen.add(String(point.x));
      if (!labels.includes(String(point.x))) labels.push(String(point.x));
      allValues.push(point.y);
    }
  }
  if (labels.length > (chart_type === 'bar' ? 50 : 200)) throw invalid();
  let min = Math.min(...allValues), max = Math.max(...allValues);
  const positiveBars = chart_type === 'bar' && min >= 0;
  const negativeBars = chart_type === 'bar' && max <= 0 && min < 0;
  if (chart_type === 'bar') { min = Math.min(0, min); max = Math.max(0, max); }
  if (max === min) { min -= 1; max += 1; }
  const span = max - min;
  min = positiveBars ? 0 : min - span * 0.07;
  max = negativeBars ? 0 : max + span * 0.07;
  const left = 100, top = 90, width = 820, height = 420;
  const x = label => left + (labels.indexOf(String(label)) + 0.5) * width / labels.length;
  const y = value => top + height - (value - min) / (max - min) * height;
  const pieces = [`<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="650" viewBox="0 0 1000 650"><rect width="1000" height="650" fill="white"/><g font-family="sans-serif" fill="#263341"><text x="50" y="42" font-size="24" font-weight="bold">${escape(title)}</text>`];
  for (let tick = 0; tick <= 5; tick++) {
    const value = min + tick * (max - min) / 5, yy = y(value);
    pieces.push(`<line x1="${left}" y1="${yy}" x2="${left + width}" y2="${yy}" stroke="#e5e9ee"/><text x="${left - 10}" y="${yy + 5}" font-size="13" text-anchor="end">${escape(Number(value.toPrecision(4)))}</text>`);
  }
  const stride = Math.max(1, Math.ceil(labels.length / 8));
  labels.forEach((label, index) => { if (index % stride === 0 || index === labels.length - 1) pieces.push(`<text x="${x(label)}" y="540" text-anchor="middle" font-size="12">${escape(label.slice(0, 18))}</text>`); });
  pieces.push(`<text x="510" y="574" text-anchor="middle" font-size="15">${escape(x_label)}</text><text transform="translate(24 300) rotate(-90)" text-anchor="middle" font-size="15">${escape(y_label)}</text>`);
  series.forEach((item, index) => {
    const color = COLORS[index];
    if (chart_type === 'line') {
      pieces.push(`<polyline fill="none" stroke="${color}" stroke-width="3" points="${item.points.map(point => `${x(point.x)},${y(point.y)}`).join(' ')}"/>`);
      for (const point of item.points) pieces.push(`<circle cx="${x(point.x)}" cy="${y(point.y)}" r="3" fill="${color}"/>`);
    } else {
      const barWidth = width / labels.length * 0.8 / series.length;
      for (const point of item.points) pieces.push(`<rect x="${x(point.x) - width / labels.length * 0.4 + index * barWidth}" y="${Math.min(y(0), y(point.y))}" width="${barWidth}" height="${Math.max(0.5, Math.abs(y(point.y) - y(0)))}" fill="${color}"/>`);
    }
    pieces.push(`<rect x="${100 + index * 220}" y="610" width="14" height="14" fill="${color}"/><text x="${122 + index * 220}" y="623" font-size="13">${escape(item.name.slice(0, 24))}</text>`);
  });
  pieces.push('</g></svg>');
  const attachment = Buffer.from(new Resvg(pieces.join(''), { font: { loadSystemFonts: true, defaultFontFamily: 'sans-serif' } }).render().asPng());
  return validatedArtifact('chart.png', attachment, 'base64');
}

export class ArtifactCollector {
  #safety;
  constructor({ safety = {} } = {}) { this.#safety = safety; }
  #files = [];
  #hashes = new Set();
  #total = 0;
  #warnings = new Set();
  #pythonExports = new Map();
  add(artifact, safety = this.#safety) {
    if (!artifact || !Buffer.isBuffer(artifact.attachment)) throw invalid();
    const verified = validatedArtifact(artifact.name, artifact.attachment, 'base64');
    assertSafeText(verified.name, safety);
    if (verified.contentType.startsWith('text/') || verified.contentType === 'application/json') {
      assertSafeText(new TextDecoder('utf-8', { fatal: true }).decode(verified.attachment), safety);
    }
    const hash = createHash('sha256').update(verified.attachment).digest('hex');
    if (this.#hashes.has(hash)) return { filename: this.#files.find(file => file.hash === hash).name, bytes: verified.attachment.length, duplicate: true };
    if (this.#files.length >= MAX_ARTIFACT_FILES || this.#total + verified.attachment.length > MAX_ARTIFACT_TOTAL_BYTES) {
      this.#warnings.add('Some exports exceeded the limit of three files or 3 MiB combined and were not attached.');
      return { error: 'Export limit reached; this file was not attached.' };
    }
    const original = verified.name;
    let suffix = 2;
    while (this.#files.some(file => file.name === verified.name)) {
      const dot = original.lastIndexOf('.');
      verified.name = `${original.slice(0, dot)}-${suffix++}${original.slice(dot)}`;
    }
    this.#files.push({ ...verified, hash }); this.#hashes.add(hash); this.#total += verified.attachment.length;
    return { filename: verified.name, bytes: verified.attachment.length, attached: true };
  }
  collectPython(output, safety = this.#safety) {
    for (const item of output) {
      if (item?.type !== 'code_interpreter_call' || item.status !== 'completed' || !Array.isArray(item.outputs)) continue;
      for (const entry of item.outputs) {
        if (entry?.type !== 'logs' || typeof entry.logs !== 'string' || entry.logs.length > 5 * MAX_ARTIFACT_BYTES) continue;
        let logs;
        try { logs = JSON.parse(entry.logs); } catch { continue; }
        if (logs.exit_code !== 0 || typeof logs.stdout !== 'string') continue;
        for (const line of logs.stdout.split(/\r?\n/)) {
          if (!line.startsWith(MARKER)) continue;
          const key = createHash('sha256').update(line).digest('hex');
          try {
            const envelope = JSON.parse(line.slice(MARKER.length));
            if (!envelope || Object.keys(envelope).sort().join(',') !== 'base64,filename,mime_type' || typeof envelope.mime_type !== 'string') throw invalid();
            const artifact = exportFile({ filename: envelope.filename, content: envelope.base64, encoding: 'base64' });
            if (artifact.contentType !== envelope.mime_type) throw invalid();
            const metadata = this.add(artifact, safety);
            this.#pythonExports.set(key, metadata.error ? { attached: false, error: 'Export limit reached.' } :
              { filename: metadata.filename, bytes: metadata.bytes, attached: true });
          } catch {
            this.#pythonExports.set(key, { attached: false, error: 'Invalid or unsupported export.' });
            this.#warnings.add('A Python export was invalid, unsupported, or larger than 1 MiB and was not attached.');
          }
        }
      }
    }
  }
  replayOutput(output) {
    // File bytes belong in Discord attachments, not in a paid follow-up prompt.
    // Keep IDs, encrypted reasoning, code and ordinary stdout unchanged; clone
    // only log entries containing export envelopes from the provider response.
    return output.map(item => {
      if (item?.type !== 'code_interpreter_call' || !Array.isArray(item.outputs)) return item;
      let changed = false;
      const outputs = item.outputs.map(entry => {
        if (entry?.type !== 'logs' || typeof entry.logs !== 'string' || !entry.logs.includes(MARKER)) return entry;
        let logs;
        try { logs = JSON.parse(entry.logs); } catch { return entry; }
        if (typeof logs.stdout !== 'string') return entry;
        let replaced = false;
        const stdout = logs.stdout.replace(/^OWAUA_ARTIFACT:[^\r\n]*/gm, line => {
          replaced = true;
          const key = createHash('sha256').update(line).digest('hex');
          const metadata = this.#pythonExports.get(key) ?? { attached: false, error: 'No validated attachment was created.' };
          return `[Owaua export: ${JSON.stringify(metadata)}]`;
        });
        if (!replaced) return entry;
        changed = true;
        return { ...entry, logs: JSON.stringify({ ...logs, stdout }) };
      });
      return changed ? { ...item, outputs } : item;
    });
  }
  replayExportCall(call, metadata) {
    if (call?.type !== 'function_call' || call.name !== 'export_file' || metadata?.error ||
      typeof metadata?.filename !== 'string' || !Number.isInteger(metadata.bytes)) return call;
    let args;
    try { args = JSON.parse(call.arguments); } catch { return call; }
    if (!args || typeof args.content !== 'string' || args.content.length <= 4096) return call;
    return { ...call, arguments: JSON.stringify({ ...args,
      content: `[Historical export already attached as ${metadata.filename} (${metadata.bytes} bytes). File payload omitted from conversation history.]` }) };
  }
  get artifacts() { return this.#files.map(({ hash, ...artifact }) => artifact); }
  get warnings() { return [...this.#warnings]; }
}

export function registerArtifactTools(registry) {
  registry.register({ name: 'export_file', description: 'Attach a downloadable file requested by the user. Text/CSV/JSON/Markdown/code use utf8. Use base64 only for actual PNG, PDF or XLSX bytes produced by hosted Python, never invented bytes. Maximum 1 MiB.',
    parameters: { type: 'object', properties: { filename: { type: 'string', maxLength: 80 }, content: { type: 'string' },
      encoding: { type: 'string', enum: ['utf8', 'base64'] } }, required: ['filename', 'content'], additionalProperties: false } },
  args => ({ artifact: exportFile(args) }));
  registry.register({ name: 'export_chart', description: 'Attach a PNG line or bar chart from supplied or hosted-Python-computed data. Run hosted Python for numerical analysis first. Up to 4 series and 200 points (50 bar categories). Never executes local code.',
    parameters: { type: 'object', properties: { title: { type: 'string', maxLength: 120 }, x_label: { type: 'string', maxLength: 120 }, y_label: { type: 'string', maxLength: 120 },
      chart_type: { type: 'string', enum: ['line', 'bar'] }, series: { type: 'array', maxItems: 4, items: { type: 'object', properties: {
        name: { type: 'string', maxLength: 80 }, points: { type: 'array', maxItems: 200, items: { type: 'object', properties: {
          x: { anyOf: [{ type: 'string' }, { type: 'number' }] }, y: { type: 'number' },
        }, required: ['x', 'y'], additionalProperties: false } },
      }, required: ['name', 'points'], additionalProperties: false } } }, required: ['title', 'series'], additionalProperties: false } },
  args => ({ artifact: exportChart(args) }));
  return registry;
}
